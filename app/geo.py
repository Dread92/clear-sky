_INDEX = []  # (stem regex, name)
for name in PLACES:
    st = _stem(name)
    stems = [re.escape(st)]
    if st.endswith("ів"):
        stems += [re.escape(st[:-2] + "ов"), re.escape(st[:-2] + "ев")]
    elif st.endswith("їв"):
        stems.append(re.escape(st[:-2] + "єв"))
    elif st.endswith("піл"):
        stems.append(re.escape(st[:-3] + "пол"))
    elif st.endswith("ін"):
        stems.append(re.escape(st[:-2] + "ен"))
    elif st.endswith("ец"):
        stems.append(re.escape(st[:-2] + "ц"))
    elif st.endswith("ок"):
        stems.append(re.escape(st[:-2] + "к"))
    if " " in st and "(" not in name and all(len(w) >= 3 for w in st.split()):
        # multi-word names: every word declines ("Велику Димерку", "Великої Димерки")
        stems.append(r"\b" + r"\s+".join(re.escape(w.rstrip(VOWELS) if len(w.rstrip(VOWELS)) >= 3 else w) + r"[а-яіїєґ']{0,3}" for w in st.split()))
    for a in ALT.get(name, []):
        stems.append(a if "\\b" in a else re.escape(a.strip()))
    for s in stems:
        if len(s.replace("\\", "")) < 4 and "\\b" not in s:
            continue
        _INDEX.append((re.compile(r"(?<![а-яіїєґ'\-])" + s + r"[а-яіїєґ']{0,3}(?![а-яіїєґ'\-])"), name))
_INDEX.sort(key=lambda t: -len(t[0].pattern))


def bearing(lon1, lat1, lon2, lat2):
    y = math.sin(math.radians(lon2 - lon1)) * math.cos(math.radians(lat2))
    x = math.cos(math.radians(lat1)) * math.sin(math.radians(lat2)) - math.sin(math.radians(lat1)) * math.cos(math.radians(lat2)) * math.cos(math.radians(lon2 - lon1))
    return (math.degrees(math.atan2(y, x)) + 360) % 360


def _find_places(text, ctx_uid=None):
    """Return list of (start, end, name) for places mentioned in text, non-overlapping.
    Ambiguous names (same stem in several oblasts) are resolved with ctx_uid, else the plain (unparenthesised) entry."""
    spans = {}
    for rx, name in _INDEX:
        for m in rx.finditer(text):
            key = (m.start(), m.end())
            spans.setdefault(key, []).append(name)
    # drop spans overlapped by a longer span
    keys = sorted(spans, key=lambda k: (k[0], -(k[1] - k[0])))
    found = []
    taken = []
    for k in keys:
        if any(s < k[1] and k[0] < e for s, e in taken):
            continue
        taken.append(k)
        names = spans[k]
        pick = None
        if ctx_uid:
            for n in names:
                if PLACES[n][2] == ctx_uid:
                    pick = n
                    break
        if pick is None:
            plain = [n for n in names if "(" not in n]
            pick = plain[0] if plain else names[0]
        found.append((k[0], k[1], pick))
    found.sort()
    return found


def _find_oblasts_all(text):
    res = []
    for stem, uid, lon, lat in OBLAST_ADJ:
        for m in re.finditer(stem, text):
            res.append((m.start(), uid, lon, lat))
    return sorted(res)


def _find_oblast(text):
    best = None
    for stem, uid, lon, lat in OBLAST_ADJ:
        m = re.search(stem, text)
        if m and (best is None or m.start() < best[0]):
            best = (m.start(), uid, lon, lat)
    return best


def _dir(s):
    """Compass heading (deg) from a Ukrainian phrase, or None."""
    n = "півн" in s
    so = "півд" in s
    e = "сх" in s
    w = "зах" in s
    if n and e: return 45
    if n and w: return 315
    if so and e: return 135
    if so and w: return 225
    if n: return 0
    if so: return 180
    if e: return 90
    if w: return 270
    return None


def _sub_direction_offset(text, pos):
    """'на півночі Вінниччини' -> offset (dlon, dlat) of ~70 km toward that side."""
