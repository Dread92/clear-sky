# for the 45 minutes the post stayed in the feed. Nothing in a retrospective summary is a live position.
SUMMARY_RX = re.compile(
    r"застосував|випустив|за\s+минул\w*\s+добу|минул[ої]\W*\s*ноч|в\s+ніч\s+на\s+\d|"
    r"протягом\s+ноч|за\s+ніч\b|#зведення|за\s+приблизними\s+оцінками|загалом\s+(?:випущ|застосов)", re.I)


def looks_like_summary(t):
    """A count of what was fired earlier — never a position, never a marker."""
    return bool(SUMMARY_RX.search(t))


def looks_like_news(t):
    """A post about something rather than a sighting of something — whatever threat words it contains.

    Policy and money, a long post, a retrospective tally, an event, a court case; or the voice of a report
    (who said it, what happened as a result, when). A news item that mentions ballistic missiles in its fourth
    sentence used to put a ballistic missile on the map and light the red strip telling people to shelter."""
    if NEWS_RX.search(t) or NEWS_STRONG_RX.search(t) or len(t) > NEWS_MAX_CHARS or looks_like_summary(t):
        return True
    soft = len(NEWS_SOFT_RX.findall(t))
    return soft >= 2 or (soft >= 1 and len(t) > NEWS_SOFT_LONG)


def _status_of(t):
    # An article reports no outcome, whatever words it happens to contain. A government programme mentioning
    # "знищення", a visit to a new fire station, a press release about compensation — all of them used to put
    # something on the map. This guard covers every status, not just the ones that were caught first.
    news = looks_like_news(t)
    for name, rx in STATUS_RX:
        if not rx.search(t):
            continue
        if news:
            return None
        if name == "fire" and (not FIRE_EVENT_RX.search(t) or FIRE_NONE_RX.search(t)):
            # a fire station, a fire engine, or a post that says there is NO fire. Keep looking: the same
            # post usually goes on to describe the damage, and "Пожежі немає" must not cost it its marker.
            continue
        if name == "down" and _is_ground_object(t):
            return "damage"
        return name
    # a damage report with no outcome word of its own — "пошкоджено скління та фасад", "вибито вікна"
    if DAMAGE_RX.search(t) and GROUND_RX.search(t) and not news:
        return "damage"
    return None


def _status_markers(t, status):
    """'1х зниження Троєщина' / 'По реактивам довкола Києва та Житомира чисто' → status markers at the places named."""
    mtype = "drones"
    for name, rx in TYPE_RX:
        if rx.search(t):
            mtype = name
            break
    obl = _find_oblast(t, positional=True)
    places = _find_places(t, obl[1] if obl else None)
    cnt = None
    mc = COUNT_RX.search(t)
    if mc:
        cnt = int(mc.group(1) or mc.group(2))
    out = []
    sm = next((rx.search(t) for n, rx in STATUS_RX if n == status), None)
    for s, e, name in places:
        lon, lat, uid = PLACES[name]
        out.append({"type": mtype, "status": status, "lon": round(lon, 3), "lat": round(lat, 3), "heading": None, "place": name,
                    "target": None, "count": cnt, "jet": bool(re.search(r"реактив", t)), "oblast_uid": uid,
                    "evidence": {"segment": t.strip(), "type": {"matched": sm.group(0) if sm else status, "method": "outcome keyword"},
                                 "position": {"matched": t[max(0, s - 12):e].strip(), "place": name, "method": "town in gazetteer", "confidence": "high"},
                                 "heading": None, "count": ({"matched": mc.group(0), "method": "number in text"} if mc else None)}})
    if not out and obl:
        out.append({"type": mtype, "status": status, "lon": obl[2], "lat": obl[3], "heading": None, "place": "область",
                    "target": None, "count": cnt, "jet": bool(re.search(r"реактив", t)), "oblast_uid": obl[1],
                    "evidence": {"segment": t.strip(), "type": {"matched": sm.group(0) if sm else status, "method": "outcome keyword"},
                                 "position": {"matched": t[obl[0]:obl[0] + 14], "place": "oblast", "method": "oblast centre (no town named)", "confidence": "low"},
                                 "heading": None, "count": ({"matched": mc.group(0), "method": "number in text"} if mc else None)}})
    return out


_OBL_CLAUSE = re.compile(r",\s*(?=(?:на|в|у|над|по)\s+(?:" + "|".join(sorted({a[0] for a in OBLAST_ADJ}, key=len, reverse=True)) + r"))")


ALT_RX = [
    ("descending", re.compile(r"зниж\w*|знижуєть\w*|скида\w*\s+висот\w*|пікіру\w*|захід\s+на\s+ціль|заходить\s+на\s+ціль", re.I)),
    ("climbing", re.compile(r"набира\w*\s+висот\w*|підійма\w*|піднімаєть\w*", re.I)),
    ("low", re.compile(r"\bнизьк\w*\b|низько\s+йде|на\s+малій\s+висоті|гранично\s+мал\w*\s+висот\w*", re.I)),
    ("high", re.compile(r"\bвисоко\b|на\s+велик\w*\s+висот\w*|ешелон", re.I)),
]
# The channels write the height both ways round — "висота 2200" and "2200 висота" — and in a follow-up post
# they drop the word entirely: "1600, Вороньків". All three are read; nothing is guessed when none appear.
ALT_M_RX = re.compile(r"висот\w*\s*(?:бл\.|близько|~|приблизно)?\s*(\d{2,5})\s*(м|метр\w*|км)?"
                      r"|(\d{3,5})\s*(?:м|метр\w*)?\s*висот\w*", re.I)
# ...and in kilometres, often with a decimal comma: "висота 4,4км", "висота 5км" (war_monitor on jet drones).
# Read before the metre pattern, which cannot see a single digit and read "4,4км" as nothing at all.
ALT_KM_RX = re.compile(r"висот\w*\s*(?:бл\.|близько|~|приблизно)?\s*(\d{1,2}(?:[.,]\d{1,2})?)\s*км\b"
                       r"|(\d{1,2}(?:[.,]\d{1,2})?)\s*км\s*висот\w*", re.I)
# a lone 300–9000 in a short live post is a height, not a count: counts are written "3х" or "3 шахеди"
ALT_BARE_RX = re.compile(r"(?<![\d.,\-хx×])(\d{3,4})(?!\d|[.,]\d)", re.I)


def parse_altitude(seg):
    """Altitude / vertical behaviour, ONLY when the post states it.

    No public source publishes target altitude, so this is never inferred: a drone with nothing said about its
    height gets no altitude field at all, and the UI shows nothing rather than implying 'level flight'.
    Returned dict: {"state": descending|climbing|low|high, "m": metres or None, "matched": "<the words>"}."""
    out = None
    for state, rx in ALT_RX:
        m = rx.search(seg)
        if m:
            out = {"state": state, "m": None, "matched": m.group(0)}
            break
    mk = ALT_KM_RX.search(seg)
    mm = None if mk else ALT_M_RX.search(seg)
    v = None
    if mk:
        v = int(round(float((mk.group(1) or mk.group(2)).replace(",", ".")) * 1000))
        hit = mk
    elif mm:
        v = int(mm.group(1) or mm.group(3))
        if (mm.group(2) or "").lower().startswith("км"):
            v *= 1000
        hit = mm
    if v is not None and 10 <= v <= 20000:
        out = out or {"state": None, "matched": hit.group(0)}
        out["m"] = v
        out["matched"] = hit.group(0).strip()
    return out


def parse_altitude_bare(t):
    """A follow-up post that is only a number and a place — '1600, Вороньків' — is a height report."""
    if len(t.split()) > 5 or re.search(r"висот|бпла|шахед|ракет|курс", t, re.I):
        return None
    m = ALT_BARE_RX.search(t)
    if not m:
        return None
    v = int(m.group(1))
    if 300 <= v <= 9000:
        return {"state": None, "m": v, "matched": m.group(1)}
    return None


# A post often reports clear sky AND a warning in the same breath:
#   "Чисте небо Київська область та Київ. Васильків увага ‼️"
# The places in the CLEAR sentence must never receive a threat marker — a false alarm over a city that was
# just declared clear is the worst kind of noise. Sentences are filtered before anything is parsed.
SENT_CLEAR_RX = re.compile(r"чист[еиої]\w*\s+небо|\bчисто\b|небо\s+чист|відбій|загроза\s+минула|небезпека\s+минула", re.I)


def _drop_clear_sentences(t):
    parts = re.split(r"(?<=[.!?‼])\s+", t)
    if len(parts) < 2:
        return t
    kept = [p for p in parts if not (SENT_CLEAR_RX.search(p) and not re.search(r"увага|загроз|курс|летить|йде|бпла|ракет|каб", p[SENT_CLEAR_RX.search(p).end():] if SENT_CLEAR_RX.search(p) else ""))]
    return " ".join(kept) if kept else t


_OBL_STEMS = tuple(sorted({a[0] for a in OBLAST_ADJ}, key=len, reverse=True))
_OBL_FILLER = {"область", "обл", "області", "обл-ть", "регіон"}


def _hdr_line(seg):
    return seg.strip().strip(":-\u2013\u2014\u2022 \t").strip()


def _is_oblast_header(seg):
    """True when a segment is nothing but an oblast name — a heading over the lines that follow."""
    toks = [w for w in re.findall(r"[а-яіїєґa-z']+", seg.lower()) if w not in _OBL_FILLER]
    return bool(toks) and all(w.startswith(_OBL_STEMS) for w in toks)


# ---------------------------------------------------------------------------
# Where a threat is in its life, when the post says so
# ---------------------------------------------------------------------------
# A Tu-95 moving to Olenya, bombers reaching a launch line over the Caspian, "пуски", a group crossing the
# border — the monitoring channels do report these stages, and the stage is what tells a reader whether to
# keep half an eye on it or to move now. What the channels do NOT publish is where it will land, so there is
# no "target region forecast" here and there will not be one: a stage is a thing that was reported, a
# forecast is a thing that was guessed, and only one of those belongs on this map.
#
# A phase is set ONLY when the wording carries it. No stage word, no stage — the marker simply says nothing
# about where in its flight the thing is, which is the truth in most posts.
# Weapons that outrun the filter.
#
# A Shahed crosses a 10 km ring in about three minutes; that ring is a real warning, and filtering by it
# spares somebody a dozen irrelevant alerts a night. An Iskander-M or a Kinzhal is doing Mach 5 to 10 — it
# crosses the same ring in under four seconds. By the time one is "within 10 km of you" it has arrived. A
# distance filter on these does not filter anything: it deletes the only warning there was, quietly, and the
# person never learns it existed. So they are exempt from every radius anyone can set, and they alert their
# whole region the moment they are reported.
#
# Kept deliberately short. A cruise missile at ~13 km/min still gives a useful 45 seconds inside a 10 km
# ring, and widening this list to "anything fast" would put the whole map back into every alert. Kh-59/69
# stay out for the same reason: fast for a guided missile, but the same order as a Kalibr, not ten times it.
IMMEDIATE_TYPES = frozenset({"ballistic_missiles", "mig31k_departure", "supersonic_missiles"})
# About one oblast across, and roughly two minutes of ballistic flight — the span over which "this concerns
# you" is true for a weapon of this speed. It is a region test, never reported to anyone as a distance.
REGION_ALERT_KM = 150.0


def is_immediate(mtype):
    """Does this weapon cross a person's chosen radius faster than they can act on being told?"""
    return mtype in IMMEDIATE_TYPES


PHASE_LADDER = {
    # Ground-launched ballistic: there is no useful stage after the launch — the warning IS the launch.
    "ballistic": ["prep", "launch"],
    # Air-launched ballistic (Kinzhal): the take-off is the warning, an hour before anything is fired.
    "airlaunch": ["prep", "takeoff", "launch", "entering"],
    "cruise": ["prep", "redeploy", "takeoff", "line", "launch", "entering"],
    "uav": ["prep", "launch", "entering"],
    "kab": ["takeoff", "line", "drop", "exit"],
}
PHASE_FAMILY = {
    "ballistic_missiles": "ballistic",
    "mig31k_departure": "airlaunch",
    "cruise_missiles": "cruise", "banderol_missiles": "cruise", "unspecified_missiles": "cruise",
    "supersonic_missiles": "cruise",
    "strategic_aircraft_activity": "cruise",
    "drones": "uav",
    "guided_aerial_bombs": "kab", "tactic_aircraft_activity": "kab",
}
# A launch somebody expects is not a launch that happened. This is tested before a bare "пуск", and
# again as a guard in detect_phase(), because reporting a possibility as a fact is the one error that
# cannot be walked back.
PREP_HEDGE_RX = re.compile(
    r"ймовірн|можлив|може\s+(?:відбу|ста|бути)|очікуєт|очікуєм|прогнозу|загроз|ризик"
    r"|не\s+виключ|готуют\w*\s+до|будь-як\w*\s+момент", re.I)
_SENT_SPLIT_RX = re.compile(r"[.!?\n;]+")


def _hedged(text, at):
    """Is the launch word inside a sentence that hedges? Scoped to the sentence on purpose: a post can
    state one launch and speculate about the next, and only the speculation should be downgraded."""
    left = max((m.end() for m in _SENT_SPLIT_RX.finditer(text, 0, at)), default=0)
    right = _SENT_SPLIT_RX.search(text, at)
    return bool(PREP_HEDGE_RX.search(text[left:right.start() if right else len(text)]))
# Order matters: the most specific wording wins. "вийшли з рубежу" is an exit, not a launch line. And a
# hedged launch is tested before a bare one, so "ймовірний пуск" can never be reported as a launch.
PHASE_RX = [
    ("exit", re.compile(r"відхід|відійшл|відход\w*|вийшл[аио]\s+з\s+руб[іе]ж|лягли\s+на\s+зворотн"
                        r"|повертают\w*\s+на\s+аеродром", re.I)),
    ("drop", re.compile(r"\bскид\w*|застосуванн\w*\s+каб"
                        r"|пуск\w*\s+(?:керован\w*\s+авіаційн\w*\s+бомб|каб)", re.I)),
    ("line", re.compile(r"руб[іе]ж\w*\s+пуск|на\s+руб[іе]ж|вихід\s+на\s+руб[іе]ж|в\s+зон[іи]\s+пуск", re.I)),
    ("entering", re.compile(r"увійшл|зайшл\w*\s+(?:в|у)\s+повітрян|перетнул\w*\s+(?:держ\w*\s+)?кордон"
                            r"|вхід\s+(?:в|у)\s+повітрян|перетин\w*\s+кордон", re.I)),
    ("launch", re.compile(r"\b(?:за)?пуск(?:и|у|ів|ом|ами|ах|а)?\b|стартувал", re.I)),
    ("takeoff", re.compile(r"\bзліт\b|злет[іи]л|піднял\w*\s+(?:в|у)\s+повітр|борт\w*\s+(?:в|у)\s+повітр"
                           r"|у\s+повітрі\b", re.I)),
    ("redeploy", re.compile(r"перебазув|передислок|завантаж\w*\s+(?:ракет|боєприпас)|озброюют|підвіс\w*\s+ракет", re.I)),
    ("prep", re.compile(r"активн[іи]ст|готуют|підготовк", re.I)),
]


def detect_phase(text, mtype=None):
    """The stage this post reports, or None when it reports no stage at all.

    When a type is given, a stage that does not belong to that weapon's life is discarded: a Shahed has no
    "drop", a KAB has no "entering". Reading one across families is how a plausible word becomes a wrong fact.
    """
    t = _norm(text)
    fam = PHASE_FAMILY.get(mtype) if mtype else None
    allowed = PHASE_LADDER.get(fam) if fam else None
    for key, rx in PHASE_RX:
        if not rx.search(t):
            continue
        if key == "launch" and all(_hedged(t, m.start()) for m in rx.finditer(t)):
            # Every launch this post mentions is hedged. Never harden that into a launch, even if
            # "prep" is not a rung on this ladder — one unhedged mention anywhere is enough to keep it.
            key = "prep"
        if allowed is not None and key not in allowed:
            continue
        return key
    return None


def phase_progress(mtype, phase):
    """(index, total) along that weapon's ladder, for a UI that wants to show how far along it is."""
    fam = PHASE_FAMILY.get(mtype)
    ladder = PHASE_LADDER.get(fam) if fam else None
    if not ladder or phase not in ladder:
        return None
    return (ladder.index(phase) + 1, len(ladder))


def parse_post(text):
    """Return a list of marker dicts for one post (may be empty)."""
    t = _norm(text)
    t = _drop_clear_sentences(t)
    if CLEAR_RX.search(t) and not re.search(r"бпла|ракет|каб", t):
        return []
    # alert announcements ("відбій … ракетна загроза", "повітряна тривога! дронова загроза", "загроза застосування
    # балістики") describe an ALERT, not a target position — never a marker unless the sentence says where it flies
    if ALERT_MSG_RX.search(t) and not MOVE_RX.search(t):
        return []
    # a retrospective tally of the night, or an article: a report, not a sky — no marker of any kind
    if looks_like_news(t):
        return []
    st = _status_of(t)
    if st and not re.search(r"курс|у бік|напрям|летить|летять|перелітає", t):
        return _status_markers(t, st)
    mtype = None
    type_ev = None
    for name, rx in TYPE_RX:
        mm = rx.search(t)
        if mm:
            mtype = name
            type_ev = {"matched": mm.group(0), "method": "keyword"}
            break
    likely = None
    if not mtype and (COUNT_RX.search(t) or "🅿" in text or "⚠" in text or "‼" in text or parse_altitude(t)) and not re.search(r"чисто|збит|знищен|мінус", t):
        mtype = "unknown"
        # the type is not stated, but a height or a bare count on these channels almost always means a drone:
        # carried as a likelihood, never as the type itself
        likely = "drones"
        type_ev = {"matched": None, "method": "the post does not say what it is; most likely a drone, from what this channel reports", "confidence": "none"}
    if not mtype:
        return []
    # split into segments: newlines, ';', ' та ' , ' також '
    segs = [s.strip() for s in re.split(r"\n|;|\bтакож\b|(?<=[а-яіїє.])\s+та\s+(?=[а-яіїє])", t) if s.strip()]
    # a clause that starts a new oblast (", на Одещині біля …") is its own report — one marker, one justification
    segs = [x.strip() for s_ in segs for x in _OBL_CLAUSE.split(s_) if x.strip()]
    lines = {_hdr_line(x) for x in re.split(r"\n|;", t)}
    markers = []
    ctx_obl = _find_oblast(t, positional=True)
    cur_obl = ctx_obl
    post_type, post_type_ev = mtype, type_ev
    for seg in segs:
        if ALERT_MSG_RX.search(seg) and not MOVE_RX.search(seg):
            continue
        seg_obl = _find_oblast(seg, positional=True)
        # "🛵 Київщина" on a line of its own introduces the lines under it — it is a heading, not a sighting.
        # Drawing it put a marker on the oblast centre (for Kyiv oblast, 100 km south of the Chornobyl zone
        # the very next line was talking about) every single time one of these posts came in.
        # It must be a WHOLE LINE with something under it: "КАБи на Сумщину та Донеччину" is a list of two
        # places, and its second half is a report in its own right, not a heading over anything.
        if seg_obl and len(segs) > 1 and _hdr_line(seg) in lines and _is_oblast_header(seg):
            cur_obl = seg_obl
            continue
        obl = seg_obl or cur_obl
        # The type belongs to the line, not to the post. Resolving it once over the whole text meant one word
        # anywhere coloured everything: "Київщина - реактивний на Кагарлик - 7 бандеролей на зону ЧАЕС" drew
        # the jet drone over Kaharlyk as a Banderol. A line that names no weapon still inherits the post's.
        mtype, type_ev = post_type, post_type_ev
        for name, rx in TYPE_RX:
            sm_ = rx.search(seg)
            if sm_:
                mtype, type_ev = name, {"matched": sm_.group(0), "method": "keyword"}
                break
        places = _find_places(seg, obl[1] if obl else None)
        # split at course keyword
        class _M:  # pseudo-match at a position
            def __init__(self, p): self._p = p
            def start(self): return self._p
        cm = re.search(r"(?:від|з)\s+[а-яіїє'\- ]{3,40}?\s+(на\s+)", seg)
        if cm:
            cm = _M(cm.start(1))
        else:
            cm = re.search(r"кур(?:с|сом)\b|напрям|летить|летять|рухаєт|у бік|в бік|в сторону|прямує|заходить на|заходять на", seg)
        if not cm:
            # no course word, but a place it is going to: "реактивний БпЛА на Васильків з північного заходу"
            dst = next((p for p in places if _place_role(seg, p) == "dest"), None)
            if dst:
                cm = _M(dst[0])
        cpos = cm.start() if cm else len(seg)
        origin = [p for p in places if p[0] < cpos]
        target = [p for p in places if p[0] >= cpos]
        lon = lat = None
        where = None
        from_heading = None
        origin_end = 0
        ev = {"segment": seg.strip(), "type": type_ev, "position": None, "heading": None, "count": None}
        mf = re.search(r"(?:зі сторони|з боку|з напрямку|від)\s+", seg[:cpos])
        if mf:
            before = [p for p in origin if p[1] <= mf.start()]
            after_ = [p for p in origin if p[0] >= mf.end() and p[0] < mf.end() + 45]
            if before and after_:
                n = before[-1][2]
                lon, lat, _ = PLACES[n]
                where = n
                origin_end = before[-1][1]
                ev["position"] = {"matched": seg[before[-1][0]:before[-1][1]], "place": n, "method": "town in gazetteer", "confidence": "high"}
                fl, ft, _ = PLACES[after_[0][2]]
                if (fl, ft) != (lon, lat):
                    from_heading = bearing(fl, ft, lon, lat)
                    ev["heading"] = {"matched": seg[mf.start():after_[0][1]], "method": f"bearing from {after_[0][2]} to {n} ('from the direction of')", "confidence": "medium"}
            elif before and not after_:
                fo = _find_oblast(seg[mf.end():mf.end() + 45])
                if fo:
                    n = before[-1][2]
                    lon, lat, _ = PLACES[n]
                    where = n
                    origin_end = before[-1][1]
                    ev["position"] = {"matched": seg[before[-1][0]:before[-1][1]], "place": n, "method": "town in gazetteer", "confidence": "high"}
                    from_heading = bearing(fo[2], fo[3], lon, lat)
                    ev["heading"] = {"matched": seg[mf.start():mf.end() + 45].strip(), "method": "bearing from the named oblast's centre", "confidence": "low"}
        if lon is None and origin:
            n = origin[-1][2] if re.search(r"поблизу|повз|біля|в районі|р-ні|н\.п\.|через|над|від|довкола|навколо", seg[:cpos]) else origin[0][2]
            lon, lat, _ = PLACES[n]
            where = n
            pm = [p for p in origin if p[2] == n][-1]
            origin_end = pm[1]
            ws = seg.rfind(" ", 0, max(0, pm[0] - 10)) + 1
            ev["position"] = {"matched": seg[ws:pm[1]].strip(), "place": n, "method": "town in gazetteer" + (" (parenthesised/ambiguous name resolved by oblast context)" if "(" in n else ""), "confidence": "high"}
        # "Київщина: БпЛА на Васильків з північного заходу": the oblast is only the heading of the post. Drawing
        # the target at the oblast's centre put it somewhere nobody named, turned toward Vasylkiv from the wrong
        # side. A town in that same oblast that it is heading to is the one place the post did name.
        in_obl = bool(obl) and bool(target) and bool(cm) and (
            PLACES[target[0][2]][2] == obl[1] or {PLACES[target[0][2]][2], obl[1]} <= {"31", "14"})
        if lon is None and in_obl:
            pass
        elif lon is None and obl and obl[0] < cpos:
            dx, dy = _sub_direction_offset(seg, obl[0])
            lon, lat = obl[2] + dx, obl[3] + dy
            where = "область"
            origin_end = obl[0]
            ev["position"] = {"matched": seg[seg.rfind(" ", 0, max(0, obl[0] - 10)) + 1:obl[0] + 14].strip(), "place": "oblast", "method": "oblast centre" + (" shifted ~70 km toward the stated side" if (dx or dy) else " (no town named)"), "confidence": "low"}
        elif lon is None and obl:
            lon, lat = obl[2], obl[3]
            where = "область"
            origin_end = obl[0]
            q = oblast_quadrant(seg) or oblast_quadrant(t)
            if q:
                lon, lat = lon + q[0], lat + q[1]
                quad = q[2]
                ev["position"] = {"matched": seg[obl[0]:obl[0] + 14].strip(), "place": "oblast", "quad": quad,
                                  "method": "the part of the oblast the post named (no town given)", "confidence": "low"}
            else:
                ev["position"] = {"matched": seg[obl[0]:obl[0] + 14].strip(), "place": "oblast", "method": "oblast centre (no town named)", "confidence": "low"}
        approaching = False
        if lon is None and target and cm:
            tn = target[0][2]
            lon, lat, _ = PLACES[tn]
            where = "→ " + tn
            approaching = True
            ev["position"] = {"matched": seg[cpos:target[0][1]].strip(), "place": tn, "method": "no origin named — drawn at the destination it is heading to", "confidence": "low"}
        if lon is None:
            continue
        heading = None
        tgt_name = None
        tgt_uid = None
        if cm:
            after = seg[cpos:]
            tobl = None
            origin_obl_uid = obl[1] if (where == "область" and obl) else None
            for cand in _find_oblasts_all(after):
                if cand[1] != origin_obl_uid:
                    tobl = cand
                    break
            if target and not approaching and (not tobl or target[0][0] - cpos < tobl[0]):
                tgt_name = target[0][2]
                tl, tt, _ = PLACES[tgt_name]
                heading = bearing(lon, lat, tl, tt)
                ev["heading"] = {"matched": seg[cpos:target[0][1]].strip(), "method": f"bearing from {where} to the named destination {tgt_name}", "confidence": "high"}
            elif approaching:
                tgt_name = target[0][2]
            elif tobl:
                # "Далі Київщина" — the app knows exactly which oblast was named, so it says so. Showing
                # "neighbouring oblast" threw that away and left the reader guessing at the one thing the
                # post was clear about.
                tgt_name = "область"
                tgt_uid = tobl[1]
                heading = bearing(lon, lat, tobl[2], tobl[3])
                ev["heading"] = {"matched": seg[cpos:cpos + tobl[0] + 14].strip(), "method": "bearing toward the named oblast's centre", "confidence": "medium"}
            fc = _FROM_COMPASS.search(after)
            if heading is None and fc and _dir(fc.group(1)) is not None:
                heading = (_dir(fc.group(1)) + 180) % 360
                ev["heading"] = {"matched": fc.group(0), "method": "'from the <compass>' reversed", "confidence": "medium"}
            if heading is None:
                heading = _dir(_FROM_COMPASS.sub(" ", after))
                if heading is not None:
                    ev["heading"] = {"matched": after.strip()[:40], "method": "compass word after 'course'", "confidence": "medium"}
            if heading is None:
                heading = _dir(seg[origin_end:cpos])
                if heading is not None:
                    ev["heading"] = {"matched": seg[origin_end:cpos].strip()[:40], "method": "compass word before 'course'", "confidence": "medium"}
        if heading is None and from_heading is not None:
            heading = from_heading
        if heading is None:
            m = re.search(r"\bз\s+([а-яіїє'-]+(?:\s+[а-яіїє'-]+)?)", seg[origin_end:])
            if m:
                frm = _dir(m.group(1))
                if frm is not None:
                    heading = (frm + 180) % 360
                    ev["heading"] = {"matched": m.group(0), "method": "'from the <compass>' reversed", "confidence": "medium"}
        if heading is None:
            ev["heading"] = {"matched": None, "method": "no course words in the sentence", "confidence": "none"}
        cnt = None
        mc = COUNT_RX.search(seg)
        if mc:
            cnt = int(mc.group(1) or mc.group(2))
            ev["count"] = {"matched": mc.group(0), "method": "number in text"}
        elif GROUP_RX.search(seg):
            cnt = 3
            ev["count"] = {"matched": GROUP_RX.search(seg).group(0), "method": "'group' → shown as ×3 (unknown size)"}
        alt = parse_altitude(seg) or parse_altitude(t)
        if alt:
            ev["altitude"] = {"matched": alt["matched"], "method": "stated in the post", "confidence": "high"}
        # The sentence first: a post can open with a general assessment and then report one specific stage.
        _ph = detect_phase(seg, mtype) or detect_phase(t, mtype)
        if _ph:
            ev["phase"] = {"matched": _ph, "method": "stage named in the post", "confidence": "high"}
        markers.append({"type": mtype, "lon": round(lon, 3), "lat": round(lat, 3), "heading": None if heading is None else round(heading),
                        "place": where, "target": tgt_name, "target_uid": tgt_uid, "count": cnt, "jet": bool(re.search(r"реактив|jet", seg)),
                        # drawn at the town it is heading to, not where it is: never moved on past it, never read as there
                        "approach": approaching,
                        "alt": alt, "likely": likely,
                        # The oblast the sentence names and the oblast the gazetteer has for the town must
                        # agree. When they do not, the town was matched wrong — that is exactly how
                        # "Харківщина: … Коломак" once drew five Shaheds over Kolomyia, 700 km west. The
                        # gazetteer's own oblast for the place it actually found always wins.
                        "oblast_uid": _uid_for(where, obl),
                        "phase": _ph, "phase_step": phase_progress(mtype, _ph),
                        "phase_ladder": PHASE_LADDER.get(PHASE_FAMILY.get(mtype)) if _ph else None,
                        "evidence": ev})
    return markers


ARROW_TYPE = {"✈": "drones", "🛵": "drones", "🏍": "drones", "🚀": "cruise_missiles", "💣": "guided_aerial_bombs", "🛩": "tactic_aircraft_activity", "🎯": "ballistic_missiles"}


def parse_arrows(text):
    """'✈️Харківщина:\n→Богодухів/р-н (3х);\n→Білий Колодязь/Шевченкове (5х).'  (povitryanatrivogaaa style)
    → one marker per arrow line: position = first place, heading toward second place."""
    t = _norm(text)
    if "→" not in t and "➡" not in t:
        return []
    out = []
    cur_type = "drones"
    cur_obl = None
    cur_head = ""
    for raw in re.split(r"\n|;", t):
        line = raw.strip(" .")
        if not line:
            continue
        for ch, ty in ARROW_TYPE.items():
            if ch in line:
                cur_type = ty
        head = re.sub(r"[→➡].*", "", line)
        o = _find_oblast(head, positional=True)
        if o and line.rstrip().endswith(":") or (o and "→" not in line and "➡" not in line):
            cur_obl = o
            cur_head = line.strip()
            continue
        if "→" not in line and "➡" not in line:
            continue
        body = re.sub(r"^[^→➡]*[→➡]\s*", "", line)
        cnt = None
        mc = re.search(r"\((\d{1,3})\s*[хx×]\)", body)
        if mc:
            cnt = int(mc.group(1))
            body = body[:mc.start()]
        parts = [p.strip() for p in body.split("/") if p.strip()]
        if not parts:
            continue
        pl = _find_places(parts[0])
        lon = lat = None
        where = None
        quad = None
        # "Одещина: ➡️Південь/Одеса" puts the oblast and the arrow on ONE line. Only a line ending in ":" used
        # to set the context, so this shape lost its oblast entirely and the whole line was dropped.
        obl = _find_oblast(parts[0], positional=True) or o or cur_obl
        if pl:
            lon, lat, _ = PLACES[pl[0][2]]
            where = pl[0][2]
        elif obl:
            lon, lat, where = obl[2], obl[3], "область"
            q = bare_quadrant(parts[0])
            if q:
                lon, lat, quad = lon + q[0], lat + q[1], q[2]
        if lon is None:
            continue
        heading = None
        tgt = None
        if len(parts) > 1:
            tp = _find_places(parts[1])
            to = _find_oblast(parts[1])
            if tp:
                tgt = tp[0][2]
                tl, tt, _ = PLACES[tgt]
                if (tl, tt) != (lon, lat):
                    heading = bearing(lon, lat, tl, tt)
            elif to:
                tgt = "область"
                heading = bearing(lon, lat, to[2], to[3])
            elif "р-н" in parts[1] or "район" in parts[1]:
                tgt = None
        ev = {"segment": (cur_head + " " + line.strip()).strip(), "type": {"matched": [c for c in ARROW_TYPE if c in line][:1] or ["✈️ default"], "method": "channel icon convention (✈️ = strike UAV)"},
              "position": dict({"matched": parts[0], "place": where,
                                "method": "town in gazetteer" if pl else "the part of the oblast the channel named (no town given)" if quad else "oblast centre (town not in gazetteer)",
                                "confidence": "high" if pl else "low"}, **({"quad": quad} if quad else {})),
              "heading": ({"matched": "→ " + parts[1], "method": "bearing from first to second place of the 'A/B' pair", "confidence": "high"} if heading is not None else {"matched": None, "method": "single place, no direction pair", "confidence": "none"}),
              "count": ({"matched": mc.group(0), "method": "number in brackets"} if mc else None)}
        out.append({"type": cur_type, "lon": round(lon, 3), "lat": round(lat, 3), "heading": None if heading is None else round(heading),
                    "place": where, "target": tgt, "count": cnt, "jet": False, "evidence": ev, "oblast_uid": (obl[1] if obl else PLACES.get(where, (0, 0, None))[2] if where else None)})
    return out


