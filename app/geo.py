THREAT_WORDS = [("ballistic_missiles", r"баліст"), ("cruise_missiles", r"крилат|ракет"), ("drones", r"дрон|бпла|шахед"),
                ("guided_aerial_bombs", r"\bкаб"), ("mig31k_departure", r"міг-?31"), ("air_defense", r"\bппо|протиповітрян")]


def _threats_from(text, level):
    t = _norm(text)
    out = []
    for ty, rx in THREAT_WORDS:
        if re.search(rx, t):
            out.append({"threat_type": ty, "level": level, "source_message": text.strip()[:160]})
    return out


def parse_koda(text):
    """Kyiv oblast military administration (@kyivoda):
    '🟡 Броварський район — повітряна тривога, жовтий рівень: Дронова загроза (жовтий рівень)'
    '🟢 Броварський район — відбій повітряної тривоги'
    → {'kind': 'start'|'end', 'name': 'Броварський район', 'level': 'yellow'|'red', 'threats': [...], 'type': 'raion'|'oblast'}"""
    t = text.strip()
    m = re.match(r"^\s*(🟡|🔴|🟢|🟠)?\s*([А-ЯІЇЄ][^—\-–\n]{3,60}?)\s*[—–-]\s*(повітряна тривога|відбій)(.*)$", t, re.S)
    if not m:
        return None
    emoji, name, what, rest = m.groups()
    name = name.strip()
    kind = "end" if what == "відбій" else "start"
    level = "red" if (emoji == "🔴" or "червон" in rest.lower()) else ("yellow" if (emoji in ("🟡", "🟠") or "жовт" in rest.lower()) else "red")
    ltype = "raion" if "район" in name.lower() else "oblast"
    msg = rest.split(":", 1)[1].strip() if ":" in rest else ""
    return {"kind": kind, "name": name, "level": level, "type": ltype, "threats": _threats_from(msg or rest, level) if kind == "start" else []}


def parse_kmda(text):
    """Kyiv city administration (@KyivCityOfficial)."""
    t = _norm(text)
    if re.search(r"відбій", t) and re.search(r"тривог", t):
        return {"kind": "end"}
    if re.search(r"оголошен[ао]\s+(дронов[ау]\s+небезпек|повітрян[ау]\s+тривог|балістичн)", t) or re.search(r"увага!.*(небезпек|тривог)", t):
        level = "yellow" if ("🟡" in text or "жовт" in t or "дронов" in t) else "red"
        return {"kind": "start", "level": level, "threats": _threats_from(text, level)}
    if re.search(r"працюють сили ппо|працює ппо", t):
        return {"kind": "threat", "threats": [{"threat_type": "air_defense", "level": "red", "source_message": text.strip()[:160]}]}
    if re.search(r"загроза застосування балістич|балістична загроза|загроза балістики", t):
        return {"kind": "threat", "threats": [{"threat_type": "ballistic_missiles", "level": "red", "source_message": text.strip()[:160]}]}
    return None


OBLAST_STEM = [("житомир", "10"), ("чернігів", "25"), ("сумськ", "20"), ("полтав", "19"), ("черкас", "24"), ("вінниц", "4"), ("київськ", "14"),
               ("харків", "22"), ("дніпропетров", "9"), ("кіровоград", "15"), ("рівнен", "5"), ("хмельниц", "3"), ("миколаїв", "17"), ("одес", "18"),
               ("запорі", "12"), ("херсон", "23"), ("донец", "28"), ("луган", "16"), ("волин", "8"), ("львів", "27"), ("тернопіл", "21"),
               ("івано", "13"), ("чернівец", "26"), ("закарпат", "11"), ("крим", "29"), ("севастопол", "30")]


_ETR_LOC = re.compile(r"^\s*(?:🟡|🔴|🟢|🟠|💣|🛸|🚀|✈️|⚠️|❗|🔥)?\s*([^()\n]{2,60}?)\s*\(([^)]*)\)\s*$")
_ETR_THREAT = [("guided_aerial_bombs", r"каб"), ("ballistic_missiles", r"баліст"), ("cruise_missiles", r"крилат|ракет"), ("drones", r"бпла|дрон|шахед"),
               ("mig31k_departure", r"міг-?31"), ("tactic_aircraft_activity", r"тактичн|авіац")]


def _etr_uid(obl, name):
    src = (obl or "").lower()
    for stem, u in OBLAST_STEM:
        if stem in src:
            return u
    nl = name.lower()
    if re.match(r"^(м\.\s*)?київ\b", nl):
        return "31"
    for stem, u in OBLAST_STEM:
        if stem in nl:
            return u
    return None


def parse_etryvoga(text):
    """@UkraineAlarmSignal (єТривога) — every raion of Ukraine. Returns a LIST of alert changes.
    Formats: '🟡 Жовтий рівень тривоги\nКорюківський район (Чернігівська обл.)\nЧернігівський район (...)'
             '🔴 Конотопський район (Сумська обл.)\nЧервоний рівень тривоги. Прямуйте в укриття!'
             '🟡 Охтирський район (Сумська обл.)\nВідбій червоної тривоги, жовта тривога ще триває.'
             '💣 Сумський район (Сумська обл.)\nЗагроза застосування КАБів.'  (threat on a raion)
             '🛸 Стецьківка (Сумська обл.)\nЗагроза застосування БПЛА.'      (settlement threat → feed only)
             '🟢 Відбій тривоги\n<locations…>' ; blocks separated by blank lines; 'Мапа тривог…' summaries ignored."""
    out = []
    for block in re.split(r"\n\s*\n", text.strip()):
        lines = [l.strip() for l in block.split("\n") if l.strip()]
        if not lines:
            continue
        low = _norm(block)
        if low.startswith("мапа тривог") or "тривог" not in low and "загроза" not in low and "укритт" not in low:
            continue
        # level / kind from the whole block
        if "🟢" in block or (re.search(r"відбій", low) and not re.search(r"ще триває", low)):
            kind, level = "end", None
        elif "🔴" in block or "червоний рівень" in low:
            kind, level = "start", "red"
        elif "🟡" in block or "жовтий рівень" in low or "жовта тривога" in low:
            kind, level = "start", "yellow"
        elif re.search(r"загроза", low):
            kind, level = "threat", None
        else:
            continue
        threats = []
        if kind == "threat":
            for ty, rx in _ETR_THREAT:
                if re.search(rx, low):
                    threats.append({"threat_type": ty, "level": "yellow", "source_message": block.strip()[:160]})
        locs = []
        for l in lines:
            m = _ETR_LOC.match(l)
            if m:
                name, obl = m.group(1).strip(" .-—–"), m.group(2)
                uid = _etr_uid(obl, name)
                if uid:
                    locs.append((name, uid))
        if not locs:
            # single-line header may carry the location itself: '🔴 Київська область. Червоний рівень…' / '🟢 м. Київ. Відбій…'
            m = re.match(r"^\s*(?:🟡|🔴|🟢|🟠)?\s*([^\n]{2,60}?)\s*[\.\-—–:]\s*(?:жовт|червон|відбій|повітрян|тривог)", lines[0], re.I)
            if m:
                name = m.group(1).strip(); uid = _etr_uid(None, name)
                if uid:
                    locs.append((name, uid))
        for name, uid in locs:
            nl = name.lower()
            ltype = "raion" if "район" in nl else ("city" if re.match(r"^(м\.\s*)?київ\b", nl) else ("oblast" if "област" in nl else "hromada"))
            if kind == "threat" and ltype != "raion":
                continue                      # settlement-level threat: feed + geo only
            if ltype == "city":
                name = "м. Київ"
            out.append({"kind": kind, "name": name, "level": level, "type": ltype, "oblast_uid": uid, "threats": threats})
    return out or None


def parse_eradar_alert(text):
    """@eRadarrua alert lines: '🟡 15:06 м.Київ - повітряна тривога!\nДронова загроза (жовтий рівень)',
    '🟢 20:09 м.Київ - відбій повітряної тривоги!\nРакетна загроза (червоний рівень)', also 'Київська область - …'."""
    m = re.match(r"^\s*(🟡|🔴|🟢|🟠)?\s*\d{1,2}:\d{2}\s+(.+?)\s*[-—–]\s*(повітряна тривога|відбій)(.*)$", text.strip(), re.S | re.I)
    if not m:
        return None
    emoji, name, what, rest = m.groups()
    nl = name.strip().lower()
    if re.match(r"^(м\.\s*)?київ\b", nl):
        uid, ltype, name = "31", "city", "м. Київ"
    else:
        uid = _etr_uid(None, name)
        if not uid:
            return None
        ltype = "raion" if "район" in nl else "oblast"
    if what.lower() == "відбій" or emoji == "🟢":
        return [{"kind": "end", "name": name.strip(), "level": None, "type": ltype, "oblast_uid": uid, "threats": []}]
    low = _norm(rest)
    level = "red" if (emoji == "🔴" or "червон" in low) else "yellow"
    return [{"kind": "start", "name": name.strip(), "level": level, "type": ltype, "oblast_uid": uid, "threats": _threats_from(rest, level)}]


def parse_city_siren(text):
    """City siren channels (@chernihiv_alert, @Zhytomyr_alert, @sumy_alert): '🟡 Жовтий рівень тривоги!',
    '🔴 Червоний рівень тривоги!', '🟢 Відбій тривоги!' — the alert of the city's raion."""
    t = _norm(text)
    if len(t) > 80:
        return None
    if "відбій" in t:
        return {"kind": "end"}
    if "червон" in t or "🔴" in text:
        return {"kind": "start", "level": "red", "threats": []}
    if "жовт" in t or "🟡" in text or "тривог" in t:
        return {"kind": "start", "level": "yellow", "threats": []}
    return None


